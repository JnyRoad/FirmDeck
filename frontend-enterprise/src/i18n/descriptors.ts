/**
 * 创建带稳定语义 ID 的消息描述对象；id 必须来自生成的 MessageId，values 使用具名参数且不会拼接进 ID。
 */
export function createMessageDescriptor<TMessageId extends MessageId>(
  id: TMessageId,
  values?: MessageValues,
): MessageDescriptor {
  return values === undefined ? { id } : { id, values: { ...values } };
}
